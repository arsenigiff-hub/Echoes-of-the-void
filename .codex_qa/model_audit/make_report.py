# ------------------------------------------------- привязка пары к фиксу ---
def pair_fix(p):
    ca, cb = p["cat_a"], p["cat_b"]
    x, y, z = p["xyz"]
    cats = {ca, cb}
    if p["type"] == "zfight":
        if cats == {"decal"}:
            return "F22"
        if "decal" in cats:
            return "F21"
        if "trim" in cats:
            return "F8" if abs(x - 5.0) < 0.6 and abs(z - 10.5) < 0.3 else "F9"
        if "floor" in cats and "floor" in cats and p["zone"] == "quarters":
            return "F3"
        if "ceil" in cats and p["zone"] == "quarters":
            return "F3"
        if p["zone"] == "quarters" and cats == {"wall"}:
            if abs(z - 7.2) < 0.3:
                return "F4"
            return "F5"
        if cats == {"shell"} and abs(z - 10.5) < 0.3:
            return "F7"
        if "ceil" in cats and "shell" in cats:
            return "F30"
